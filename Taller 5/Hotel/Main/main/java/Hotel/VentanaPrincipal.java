    private void itemSalidaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemSalidaActionPerformed
        try {
            String numText = javax.swing.JOptionPane.showInputDialog(this, "Ingrese número de habitación (1 a 10):", "Salida de huéspedes", javax.swing.JOptionPane.QUESTION_MESSAGE);
            if (numText != null) {
                int num = Integer.parseInt(numText);
                if (num < 1 || num > 10) {
                    javax.swing.JOptionPane.showMessageDialog(this, "El número de habitación debe estar entre 1 y 10", "Mensaje", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                } else if (hotel.buscarHabitaciónOcupada(num)) {
                    VentanaSalida vSalida = new VentanaSalida(hotel, num);
                    vSalida.setVisible(true);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "La habitación ingresada no se encuentra ocupada", "Mensaje", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                }
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Número o formato inválido", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_itemSalidaActionPerformed

