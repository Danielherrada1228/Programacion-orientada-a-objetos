    private void cargarDatosTabla() {
        String[][] datos = lista.obtenerMatriz();
        String[] titulos = {"NOMBRE", "APELLIDOS", "SUELDO"};

        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(datos, titulos);
        tablaNomina.setModel(model);
        lblTotal.setText("Total nómina mensual = $ " + String.format("%.2f", lista.totalNómina));
    }

