    private void itemGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_itemGuardarActionPerformed
        javax.swing.JFileChooser fc = new javax.swing.JFileChooser();
        fc.setFileSelectionMode(javax.swing.JFileChooser.DIRECTORIES_ONLY);
        int respuesta = fc.showOpenDialog(this);
        if (respuesta == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File directorio = fc.getSelectedFile();
            try {
                String contenido = empleados.convertirTexto();
                java.io.File archivo = new java.io.File(directorio.getAbsolutePath() + "\\Nómina.txt");
                java.io.FileWriter fw = new java.io.FileWriter(archivo);
                java.io.BufferedWriter bw = new java.io.BufferedWriter(fw);
                bw.write(contenido);
                bw.close();
                javax.swing.JOptionPane.showMessageDialog(this, "El archivo Nómina.txt se ha creado correctamente", "Mensaje", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el archivo", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }    }//GEN-LAST:event_itemGuardarActionPerformed

