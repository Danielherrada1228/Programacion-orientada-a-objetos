    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // 1. Capturamos lo que el usuario escribió en los campos de texto
            String nombre = txtNombre.getText();
            String apellidos = txtApellidos.getText();
            int edad = Integer.parseInt(txtEdad.getText()); // Convertimos el texto a número

            // 2. Intentamos instanciar el objeto Vendedor
            Vendedor vendedor = new Vendedor(nombre, apellidos, edad);

            // 3. Si la edad es correcta (ej. 25), el código llega hasta aquí y muestra éxito
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Vendedor creado con éxito:\n" + vendedor.nombre + " " + vendedor.apellidos,
                    "Éxito",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException ex) {
            // Si el usuario escribe letras en la edad o la deja vacía
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, ingrese un número válido en la edad.",
                    "Error de Formato",
                    javax.swing.JOptionPane.WARNING_MESSAGE);

        } catch (IllegalArgumentException ex) {
            // Si la edad es menor a 18 o mayor a 120, atrapamos la excepción aquí
            javax.swing.JOptionPane.showMessageDialog(this,
                    ex.getMessage(),
                    "Argumento Ilegal",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton2ActionPerformed

