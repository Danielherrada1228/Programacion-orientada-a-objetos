    private void btnLogaritmoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogaritmoActionPerformed
        try {
            // 1. Obtener el texto del JTextField y convertirlo a número
            double numero = Double.parseDouble(txtNumero.getText());

            // 2. Llamar a nuestra clase separada para calcular
            double resultado = CalculosNumericos.calcularLogaritmo(numero);

            // 3. Mostrar el resultado
            txtResultado.setText(String.valueOf(resultado));

        } catch (NumberFormatException e) {
            // Si el usuario escribe letras en vez de números
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Por favor, ingrese un valor numérico válido.");
        } catch (ArithmeticException e) {
            // Si ingresa un número negativo o cero (excepción lanzada por nuestra clase)
            javax.swing.JOptionPane.showMessageDialog(this, "Error Matemático: " + e.getMessage());
}    }//GEN-LAST:event_btnLogaritmoActionPerformed

    private void btnRaizActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRaizActionPerformed
        try {
            double numero = Double.parseDouble(txtNumero.getText());

            double resultado = CalculosNumericos.calcularRaiz(numero);

            txtResultado.setText(String.valueOf(resultado));

        } catch (NumberFormatException e) {
            // Si el usuario escribe letras en vez de números
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Por favor, ingrese un valor numérico válido.");
        } catch (ArithmeticException e) {
            // Si ingresa un número negativo
            javax.swing.JOptionPane.showMessageDialog(this, "Error Matemático: " + e.getMessage());
}    }//GEN-LAST:event_btnRaizActionPerformed

